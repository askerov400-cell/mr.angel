"""Короткие толчки к действию без давления и обещаний."""
from random import SystemRandom

RANDOM = SystemRandom()

VARIANTS = {
    'sport': (
        '20 минут движения: зал, быстрая прогулка или три подхода отжиманий. Начни с того, что проще.',
        'Одно действие для тела сейчас: 15 минут растяжки или лестница вместо лифта. Дальше пойдёт легче.',
        'Спорт не требует настроения. 10 минут разминки — и решишь, продолжать ли.',
    ),
    'business': (
        '30 минут на бизнес: один конкретный шаг, который двигает деньги, а не бумаги.',
        'Выбери одно: написать клиенту, поправить цену, разобрать заявку. Одно — и день не пустой.',
        'Бизнес растёт от повторяемых действий. Что повторишь сегодня?',
    ),
    'guardian': (
        '30 минут на Хранителя: один хвост — баг, коммит или проверка. Закрой его и забудь.',
        'Что давно висит в Хранителе? Возьми самый маленький хвост и добей.',
        'Хранитель кормит только тогда, когда ты его двигаешь. 25 минут фокуса?',
    ),
    'family': (
        '15 минут с детьми без телефона: разговор, игра или прогулка. Не фоном, а по-настоящему.',
        'Семья замечает не количество часов, а внимание. Пятнадцать минут только для них?',
        'Один тёплый разговор сегодня важнее идеального плана на неделю.',
    ),
}


def build(area, done=0):
    options = VARIANTS.get(area)
    if not options:
        return 'Один небольшой шаг по плану — и день засчитан.'
    line = RANDOM.choice(options)
    if done >= 3:
        return line + '\n\nСегодня по этому направлению уже отмечено: ' + str(done) + '. Держи темп.'
    return line
